"""Publish reviewable unsigned build outputs using the job's short-lived token.

The dedicated branch contains only generated diagnostics, reports and the IPA.
Authentication is passed through Git's environment, never stored in a file/log.
"""
import base64
import json
import os
import plistlib
from pathlib import Path
import re
import stat
import shutil
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
repository = os.environ["GITHUB_REPOSITORY"]
token = os.environ["GITHUB_TOKEN"]
environment = dict(os.environ)
environment.update({"GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": "http.https://github.com/.extraheader",
                    "GIT_CONFIG_VALUE_0": "AUTHORIZATION: basic " + base64.b64encode(("x-access-token:" + token).encode()).decode(),
                    "GIT_TERMINAL_PROMPT": "0"})
branch = "codex/build-artifacts"

with tempfile.TemporaryDirectory() as directory:
    work = Path(directory)
    def git(*arguments, check=True):
        return subprocess.run(["git", *arguments], cwd=work, env=environment, check=check, capture_output=True, text=True)
    git("init", "-q")
    git("remote", "add", "origin", "https://github.com/" + repository + ".git")
    existing = git("ls-remote", "--heads", "origin", branch).stdout.strip()
    if existing:
        git("fetch", "-q", "--depth=1", "origin", branch)
        git("checkout", "-q", "-b", branch, "FETCH_HEAD")
    else:
        git("checkout", "-q", "--orphan", branch)
    (work / "README.md").write_text("# PureTone build outputs\n\nGenerated by GitHub Actions. Source: https://github.com/" + repository + "/tree/main\n\n`latest.json` records the most recent attempt. `build.json` identifies the IPA's exact source revision. The IPA is unsigned and needs Sideloadly. No Apple credentials are used.\n", encoding="utf-8")
    logs = {}
    diagnostics = []
    for path in (root / "TestResults").glob("*.log"):
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        logs[path.name] = "\n".join(lines[-350:])
        for index, line in enumerate(lines):
            if re.search(r"\berror:|CMake Error|FAILED:|AssertionError|Traceback|Test Case .*failed|Testing failed|tests failed|Undefined symbols|TEST FAILED", line, re.IGNORECASE):
                diagnostics.extend(lines[max(0, index - 1):index + 5])
    metadata = {"run": os.environ["GITHUB_RUN_ID"], "commit": os.environ["GITHUB_SHA"],
                "url": "https://github.com/" + repository + "/actions/runs/" + os.environ["GITHUB_RUN_ID"],
                "job_status": os.environ.get("BUILD_JOB_STATUS"), "diagnostics": list(dict.fromkeys(diagnostics))[:250], "log_tails": logs}
    metadata["bundles"] = {}
    metadata["bundle_files"] = {}
    metadata["bundle_signature"] = {}
    apps = list((root / ".build").glob("DerivedData*/Build/Products/*/PureTone.app"))
    bundles = [path for app in apps for path in [app, *app.rglob("*.framework"), *app.rglob("*.xctest")]]
    for app in bundles:
        try:
            info = plistlib.loads((app / "Info.plist").read_bytes())
            metadata["bundles"][str(app.relative_to(root))] = {key: info.get(key) for key in ["CFBundleIdentifier", "CFBundleExecutable", "CFBundleName", "CFBundlePackageType", "MinimumOSVersion"]}
        except Exception as error:
            metadata["bundles"][str(app.relative_to(root))] = {"error": str(error)}
    for app in apps:
        metadata["bundle_files"][str(app.relative_to(root))] = [
            {"path": str(file.relative_to(app)), "mode": oct(stat.S_IMODE(file.stat().st_mode)), "size": file.stat().st_size,
             "magic": file.open("rb").read(8).hex() if file.is_file() else "directory"}
            for file in sorted(app.iterdir())
        ]
        process = subprocess.run(["codesign", "--display", "--verbose=4", str(app)], capture_output=True, text=True)
        metadata["bundle_signature"][str(app.relative_to(root))] = process.stdout + process.stderr
    (work / "latest.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for name in ["dsp.json", "codecs.json"]:
        source = root / "TestResults" / name
        if source.exists():
            shutil.copy2(source, work / name)
    ipa = root / "build/PureTone-unsigned.ipa"
    if ipa.exists():
        shutil.copy2(ipa, work / ipa.name)
        shutil.copy2(root / "build/SHA256SUMS.txt", work / "SHA256SUMS.txt")
        (work / "build.json").write_text(json.dumps({key: metadata[key] for key in ["run", "commit", "url"]}, indent=2) + "\n", encoding="utf-8")
    git("config", "user.name", "github-actions[bot]")
    git("config", "user.email", "41898282+github-actions[bot]@users.noreply.github.com")
    git("add", ".")
    git("commit", "-q", "-m", "Build " + metadata["run"] + " from " + metadata["commit"][:8])
    git("push", "-q", "origin", "HEAD:" + branch)
print("Published unsigned build diagnostics to " + branch)
